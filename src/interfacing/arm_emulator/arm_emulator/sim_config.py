"""Writes joint_command's configs for the emulator: the real files with the wrist and gripper switched on.

Generated from the repo's YAMLs each time rather than kept as copies, so they can't drift from the real
limits and gains, and exist only inside the emulator container. Only SWITCHED_ON and SIM_OVERRIDES change
(write() checks that); the real arm's wrist and gripper stay as arm_actuators.yaml sets them.

    python -m arm_emulator.sim_config OUT_DIR
"""
from __future__ import annotations

import copy
import shutil
import sys
from pathlib import Path
from typing import Any, Iterator

import yaml

from arm_emulator.config import REPO_ACTUATORS, REPO_CALIBRATION

SWITCHED_ON = (("wrist", "pitch"), ("gripper", "open_close"))
# The one value that isn't just a switch. arm_actuators.yaml's wrist still has its bench-run feed-forward,
# 2 x gravity: at wrist kp 0.244 the extra 0.18 N.m at home lifts it about 14 deg, past its 12 deg tracking
# limit, so joint_command halts the arm (scenarios/test_joint_command.py found this). Sim only, and not a
# bench result: with the real wrist switched on, this needs its own decision and bench check.
SIM_OVERRIDES = {("wrist", "pitch", "gravity_ff_scale"): 1.0}
MARKER = "generated by arm_emulator.sim_config: never mount this on the real arm"


def overlay(actuators: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(actuators)
    for group, joint in SWITCHED_ON:
        out["safety"]["left"][group][joint]["active"] = True
    for (group, joint, key), value in SIM_OVERRIDES.items():
        out["safety"]["left"][group][joint][key] = value
    out["emulator_overlay"] = MARKER
    return out


def allowed_changes() -> set[str]:
    return ({f"safety.left.{g}.{j}.active" for g, j in SWITCHED_ON} | {"emulator_overlay"}
            | {f"safety.left.{g}.{j}.{k}" for g, j, k in SIM_OVERRIDES})


def _walk(node: Any, path: str = "") -> Iterator[tuple[str, Any]]:
    if isinstance(node, dict):
        for key, value in node.items():
            yield from _walk(value, f"{path}.{key}" if path else str(key))
    else:
        yield path, node


def differences(real: dict[str, Any], sim: dict[str, Any]) -> list[str]:
    """Every leaf that differs between the two configs, as dotted paths."""
    a, b = dict(_walk(real)), dict(_walk(sim))
    return sorted(k for k in a.keys() | b.keys() if a.get(k, ...) != b.get(k, ...))


def write(out_dir: Path, actuators: Path = REPO_ACTUATORS, calibration: Path = REPO_CALIBRATION) -> None:
    real = yaml.safe_load(actuators.read_text(encoding="utf-8"))
    sim = overlay(real)
    unexpected = set(differences(real, sim)) - allowed_changes()
    if unexpected:
        raise SystemExit(f"sim config changed more than it declares: {sorted(unexpected)}")
    for (group, joint, key), value in SIM_OVERRIDES.items():
        print(f"[EMULATOR] sim-only override: {group}.{joint}.{key} = {value} "
              f"(real: {real['safety']['left'][group][joint].get(key)})")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "arm_actuators.yaml").write_text(yaml.safe_dump(sim, sort_keys=False), encoding="utf-8")
    shutil.copyfile(calibration, out_dir / "arm_calibration.yaml")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    write(Path(sys.argv[1]))
