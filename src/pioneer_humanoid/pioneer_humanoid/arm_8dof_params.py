def urdf_limits(urdf_path: str = URDF_PATH) -> dict:
    """{joint: (lower, upper)} rad/m from the URDF: the single source of the joint limits."""
    out = {}
    for joint in ET.parse(urdf_path).getroot().findall("joint"):
        lim = joint.find("limit")
        if joint.get("type") in ("revolute", "prismatic") and lim is not None:
            out[joint.get("name")] = (float(lim.get("lower")), float(lim.get("upper")))
    return out
